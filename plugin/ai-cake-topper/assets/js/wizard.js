	var upload = {
		branch: root.querySelector( '[data-role="upload-branch"]' ),
		prompt: root.querySelector( '[data-role="prompt-branch"]' ),
		actions: root.querySelector( '[data-role="generate-actions"]' ),
		file: root.querySelector( '[data-role="upload-file"]' ),
		stage: root.querySelector( '[data-role="upload-stage"]' ),
		canvas: root.querySelector( '[data-role="crop-canvas"]' ),
		previewCanvas: root.querySelector( '[data-role="crop-preview"]' ),
		save: root.querySelector( '[data-role="upload-save"]' ),
		hint: root.querySelector( '[data-role="upload-hint"]' ),
		error: root.querySelector( '[data-role="upload-error"]' ),
		zoom: root.querySelector( '[data-role="crop-zoom"]' ),
		zoomValue: root.querySelector( '[data-role="crop-zoom-value"]' ),
		warn: root.querySelector( '[data-role="crop-warn"]' )
	};

	var cropper = window.AiCakeCropper ? window.AiCakeCropper( config, {
		/**
		 * Keep the slider and the warning in step with the canvas.
		 *
		 * The slider is not the only way to zoom — the wheel and a pinch move
		 * it too — so it is driven from here rather than being treated as the
		 * source of truth. Two controls each believing they own the number is
		 * how they end up disagreeing.
		 */
		onZoom: function ( at ) {
			if ( upload.zoom ) {
				upload.zoom.max = String( Math.round( at.max * 100 ) );
				upload.zoom.value = String( Math.round( at.scale * 100 ) );
			}

			if ( upload.zoomValue ) {
				upload.zoomValue.textContent = at.scale.toFixed( 1 ).replace( '.', ',' ) + '×';
			}

			/*
			 * Zooming in takes a smaller part of the photograph, so past a
			 * point there are fewer source pixels than the print needs. Nothing
			 * on screen would betray that — the viewport is 640 px and
			 * everything looks fine at 640 px — so the customer would find out
			 * when the sheet arrived. It is a warning rather than a limit:
			 * a slightly soft picture of the right thing beats a sharp picture
			 * of the wrong thing, and that is their call to make.
			 */
			if ( upload.warn ) {
				upload.warn.textContent = at.sharp ? '' : config.i18n.cropSoft;
				upload.warn.hidden = at.sharp;
			}
		}
	} ) : null;

	/**
	 * Show the half of step 2 that belongs to the chosen source.
	 *
	 * Step 2 is the only step that differs between the four ways in (D-054),
	 * and the difference is entirely which of these two blocks is on screen.
	 */
	function showBranch() {
		var uploading = 'upload' === state.source;
		var searching = 'search' === state.source;

		if ( upload.branch ) {
			upload.branch.hidden = ! uploading;
		}

		if ( search.branch ) {
			search.branch.hidden = ! searching;
		}

		if ( upload.prompt ) {
			upload.prompt.hidden = uploading || searching;
		}

		if ( upload.actions ) {
			upload.actions.hidden = uploading || searching;
		}

		if ( uploading && cropper && upload.canvas ) {
			cropper.mount( upload.canvas, upload.previewCanvas );

			var option = currentOption();

			if ( option ) {
				cropper.setFormat( option );
			}
		}
	}

	function uploadError( message ) {
		if ( ! upload.error ) {
			return;
		}

		upload.error.textContent = message || '';
		upload.error.hidden = ! message;
	}

	/**
	 * Send the crop, and turn it into a design.
	 */
	function sendCrop() {
		if ( ! cropper || ! cropper.hasImage() ) {
			return;
		}

		uploadError( '' );

		var data = cropper.exportCrop();

		if ( '' === data ) {
			// The device could not build the canvas (D-057). Say so, rather
			// than posting a blank picture and blaming the photograph.
			uploadError( config.i18n.canvasTooBig );

			return;
		}

		upload.save.disabled = true;
		upload.hint.textContent = config.i18n.preparing;

		withNonce().then( function ( nonce ) {
			var headers = { 'Content-Type': 'application/json' };

			if ( nonce ) {
				headers['X-WP-Nonce'] = nonce;
			}

			return window.fetch( config.root + 'upload', {
				method: 'POST',
				credentials: 'same-origin',
				headers: headers,
				body: JSON.stringify( {
					image: data,
					format_type: state.type,
					format_mm: state.mm,
					product_id: config.productId
				} )
			} );
		} ).then( function ( response ) {
			return response.json().then( function ( body ) {
				if ( ! response.ok ) {
					throw new Error( body && body.message ? body.message : config.i18n.textFailed );
				}

				state.design = body.design;
				state.designLayout = body.layoutKey || null;

				if ( step2.preview && body.preview ) {
					step2.preview.src = body.preview;
				}

				if ( step2.stage ) {
					step2.stage.hidden = false;
				}

				update();
			} );
		} ).catch( function ( error ) {
			uploadError( error && error.message ? error.message : config.i18n.textFailed );
		} ).finally( function () {
			upload.save.disabled = false;
			upload.hint.textContent = '';
		} );
	}

	if ( upload.file ) {
		upload.file.addEventListener( 'change', function () {
			var chosen = upload.file.files && upload.file.files[ 0 ];

			if ( ! chosen || ! cropper ) {
				return;
			}

			uploadError( '' );
			invalidateDesign();

			cropper.load( chosen ).then( function () {
				if ( upload.stage ) {
					upload.stage.hidden = false;
				}
			} ).catch( function ( error ) {
				uploadError( error && error.message ? error.message : config.i18n.notAnImage );
			} );
		} );
	}

	if ( upload.save ) {
		upload.save.addEventListener( 'click', sendCrop );
	}

	if ( upload.zoom && cropper ) {
		// `input`, not `change` — the picture should move while the slider is
		// being dragged, not once it is let go.
		upload.zoom.addEventListener( 'input', function () {
			cropper.zoom( Number( upload.zoom.value ) / 100 );
		} );
	}

